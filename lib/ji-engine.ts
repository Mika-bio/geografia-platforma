export function detectKmzhIntent(query: string): KmzhGenerateInput | null {
  const q = normalize(query);
  if (!/(кмж|қысқа мерзімді|sabak|сабақ жоспар|жоспар жаса|кмж жаса)/.test(q)) {
    return null;
  }
  const synyp: 8 | 9 = /9\s*сын|9\s*класс|сын[ыi]п\s*9/.test(q) ? 9 : 8;
  let takyryp = query
    .replace(/.*(тақырып[ыі]?|takырып|topic)\s*[:\-–]?\s*/i, "")
    .replace(/кмж|қысқа мерзімді жоспар|жаса|жаз|құрастыр/gi, "")
    .replace(/\d\s*сынып/gi, "")
    .trim();
  if (takyryp.length < 3) {
    const topic = allTopics.find((t) => q.includes(normalize(t.title)));
    takyryp = topic?.title || (synyp === 8 ? "География ғылымының салалары" : "Қазақстандық географтардың зерттеулері");
  }
  return { synyp, takyryp };
}

export function answerOffline(query: string): JiAnswer {
  const trimmed = query.trim();
  if (!trimmed) {
    return {
      kind: "qa",
      source: "offline",
      text: formatStructured(
        "Сұрақ жоқ",
        "Сұрағыңызды жазыңыз — географиялық тапсырмаға жауап беремін.",
        "Кез келген тапсырманы, тест сұрағын немесе КМЖ сұранысын қоюға болады.",
        ["Сұрақты енгізіңіз", "Жіберу батырмасын басыңыз"]
      ),
    };
  }

  const kmzh = detectKmzhIntent(trimmed);
  if (kmzh) {
    const doc = generateKmzhStructured(kmzh);
    return {
      kind: "kmzh",
      source: "offline",
      text: kmzhToPlainText(doc),
    };
  }

  const knowledge = allKnowledge();
  let best: KnowledgeEntry | null = null;
  let bestScore = 0;
  for (const entry of knowledge) {
    const s = scoreMatch(trimmed, entry.keys);
    // also score title
    const ts = scoreMatch(trimmed, [entry.title]);
    const total = s + ts;
    if (total > bestScore) {
      bestScore = total;
      best = entry;
    }
  }

  if (best && bestScore >= 4) {
    return {
      kind: "qa",
      source: "offline",
      text: formatStructured(best.title, best.answer, best.explanation, best.steps),
    };
  }

  return {
    kind: "qa",
    source: "offline",
    text: heuristicAnswer(trimmed),
  };
}

