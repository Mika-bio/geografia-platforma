function normalize(s: string): string {
  return s
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[«»"'`]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function scoreMatch(query: string, keys: string[]): number {
  const q = normalize(query);
  let score = 0;
  for (const k of keys) {
    const nk = normalize(k);
    if (!nk) continue;
    if (q.includes(nk)) score += nk.length > 6 ? 6 : 4;
    else {
      const parts = nk.split(" ").filter((p) => p.length > 3);
      for (const p of parts) {
        if (q.includes(p)) score += 2;
      }
    }
  }
  return score;
}

function buildTopicKnowledge(): KnowledgeEntry[] {
  return allTopics.map((t) => {
    const theory = (t.theory || []).join(" ");
    const practice = (t.practice || [])
      .slice(0, 2)
      .map((p) => `${p.question} → ${(p.options && p.options[p.answer]) || ""} (${p.explanation || ""})`)
      .join(" ");
    return {
      keys: [t.title, t.category, ...(t.theory || []).slice(0, 2).map((x) => x.slice(0, 40))],
      title: t.title,
      answer: theory || `${t.title} тақырыбы бойынша негізгі ұғымдарды меңгеру қажет.`,
      explanation: practice || `Сынып: ${t.grade}. Санат: ${t.category}.`,
      steps: [
        `${t.title} негізгі ұғымын өз сөзіңізбен түсіндіріңіз.`,
        "Карта немесе кестеден мысал келтіріңіз.",
        "Қазақстанға қатысты байланыс жасаңыз.",
        "Қысқа қорытынды жазыңыз.",
      ],
    };
  });
}

