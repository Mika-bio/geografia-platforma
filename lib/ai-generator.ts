import { getAllSections, getSectionById } from "./curriculum";

export type DocType = "КМЖ" | "БЖБ" | "ТЖБ";

export type GeneratorInput = {
  synyp: "8" | "9";
  sectionId: string;
  sabakSany: number;
  maqsat: string;
  docType: DocType;
};

export function generateDocument(input: GeneratorInput): string {
  const section = getSectionById(input.sectionId);
  const title = section?.title ?? "Таңдалған тақырып";
  const summary = section?.summary ?? "";
  const synyp = input.synyp;
  const n = Math.max(1, Math.min(12, input.sabakSany || 1));
  const goal =
    input.maqsat.trim() ||
    `${title} бойынша білім мен дағдыларды қалыптастыру`;

  if (input.docType === "КМЖ") {
    return generateKMJ(synyp, title, summary, n, goal);
  }
  if (input.docType === "БЖБ") {
    return generateBJB(synyp, title, summary, goal);
  }
  return generateTJB(synyp, title, summary, goal);
}

function generateKMJ(
  synyp: string,
  title: string,
  summary: string,
  n: number,
  goal: string
): string {
  const lessons = Array.from({ length: n }, (_, i) => {
    const num = i + 1;
    const phase =
      num === 1
        ? "Кіріспе / ынталандыру"
        : num === n
          ? "Қорытынды / рефлексия"
          : "Негізгі мазмұнды меңгеру";
    return `
### Сабақ ${num}. ${phase}

**Сабақтың тақырыбы:** ${title} (${num}/${n})

**Мақсаты:** ${goal}

**Оқу мақсаттары:**
- Тақырыптың негізгі ұғымдарын түсіндіру
- Карта/схема/кестемен жұмыс істеу
- Себеп-салдарлық байланыстарды анықтау

**Әдіс-тәсілдер:** сұрақ-жауап, топтық жұмыс, картамен жұмыс, «ой қозғау», практикалық тапсырма

**Ресурстар:** оқулық, атлас, интерактивті карта, презентация, жұмыс парағы

**Сабақ барысы:**
1. Ұйымдастыру (2–3 мин)
2. Үй тапсырмасын тексеру / алдыңғы білімді жаңғырту (5 мин)
3. Жаңа материал (${phase}) (20–25 мин)
4. Бекіту тапсырмасы (8–10 мин)
5. Рефлексия және бағалау (3–5 мин)

**Бағалау критерийлері:**
- Ұғымдарды дұрыс қолдану
- Дереккөзбен (карта/кесте) жұмыс
- Логикалық қорытынды

**Үй тапсырмасы:** қысқа жазба / схема құру / 3 сұраққа жауап
`.trim();
  }).join("\n\n---\n\n");

  return `# Қысқа мерзімді жоспар (КМЖ)

**Пән:** География  
**Сынып:** ${synyp}  
**Тақырып:** ${title}  
**Сабақ саны:** ${n}  
**Жалпы мақсат:** ${goal}

## Тақырыпқа қысқаша шолу
${summary || "Оқулық мазмұнына сәйкес негізгі ұғымдар мен заңдылықтар қарастырылады."}

## Сабақтар

${lessons}

## Қалыптастырушы бағалау үлгісі
| Деңгей | Сипаттама |
|--------|-----------|
| Жоғары | Түсінікті түсіндіреді, мысал келтіреді, картаны дұрыс оқиды |
| Орта | Негізгі ұғымдарды біледі, көмекпен талдайды |
| Төмен | Қолдау қажет, негізгі терминдерді қайталау керек |

---
*«География Әлемі» платформасында жасалды — мұғалім қажетіне қарай өңдеңіз.*
`;
}

function generateBJB(
  synyp: string,
  title: string,
  summary: string,
  goal: string
): string {
  return `# Бөлім бойынша білімді бағалау (БЖБ)

**Пән:** География · **Сынып:** ${synyp}  
**Бөлім / тақырып:** ${title}  
**Мақсат:** ${goal}

## Қысқаша мазмұн
${summary || "Бөлімнің негізгі ұғымдары мен дағдылары тексеріледі."}

## Бағалау мақсаттары
1. Негізгі терминдер мен ұғымдарды білу
2. Карта, график, кестені интерпретациялау
3. Себеп-салдарды түсіндіру
4. Практикалық есеп/тапсырманы орындау

## Тапсырма құрылымы (40–45 мин)

### I. Тест (10 ұпай)
1. Негізгі ұғымға қатысты сұрақ (1 ұпай)
2. Карта элементін анықтау (1 ұпай)
3. Процесс/құбылысты таңдау (1 ұпай)
4. Қазақстан мысалы (1 ұпай)
5. Себеп-салдар (1 ұпай)
6–10. Қосымша 5 сұрақ (тақырыпқа сай)

### II. Қысқа жауап (10 ұпай)
1. Терминді өз сөзіңізбен түсіндіріңіз (3 ұпай)
2. Карта/диаграмма бойынша 2 қорытынды жазыңыз (4 ұпай)
3. Қазақстанға қатысты мысал келтіріңіз (3 ұпай)

### III. Кеңейтілген жауап (10 ұпай)
**Тапсырма:** «${title}» тақырыбы бойынша себеп-салдарлық схема құрып, 2–3 сөйлеммен қорытындылаңыз.

**Критерийлер:**
- Дұрыстық (4)
- Логика / байланыс (3)
- Мысал / қолданыс (3)

## Үлгі сұрақтар
1. ${title} бойынша негізгі ұғымды анықтаңыз.
2. Картадан қажетті нысанды табыңыз және сипаттаңыз.
3. Неліктен бұл құбылыс Қазақстанда маңызды?
4. Екі аймақты салыстырыңыз (кесте).
5. Экологиялық/практикалық ұсыныс беріңіз.

## Бағалау шкаласы
| Ұпай | Баға |
|------|------|
| 27–30 | 5 |
| 22–26 | 4 |
| 15–21 | 3 |
| <15 | Қайталау ұсынылады |

## Қатемен жұмыс
Қате жауаптар бойынша: терминдер сөздігі + карта практикасы + 1 қысқа эссе (10–12 сөйлем).

---
*«География Әлемі» — БЖБ үлгісі. Нақты сұрақтарды сынып деңгейіне бейімдеңіз.*
`;
}

function generateTJB(
  synyp: string,
  title: string,
  summary: string,
  goal: string
): string {
  const related = getAllSections()
    .filter((s) => s.id !== title)
    .slice(0, 5)
    .map((s) => s.title)
    .join("; ");

  return `# Тоқсандық жиынтық бағалау (ТЖБ)

**Пән:** География · **Сынып:** ${synyp}  
**Негізгі тақырыптық өзек:** ${title}  
**Мақсат:** ${goal}

## Қарастырылатын мазмұн
${summary || "Тоқсан бойынша оқылған бөлімдердің интеграциясы."}

**Қосымша байланысты тақырыптар:** ${related || "Оқулық бөлімдері"}

## Спецификация (ұсыныс)

| Блок | Мазмұн | Ұпай | Уақыт |
|------|--------|------|-------|
| A | Білу / түсіну (тест) | 15 | 15 мин |
| B | Қолдану (карта, график) | 15 | 20 мин |
| C | Талдау / зерттеу | 20 | 25 мин |
| **Барлығы** |  | **50** | **60 мин** |

## A блок — үлгі сұрақтар
1. Негізгі терминдер мен анықтамалар
2. Процестердің ретін орналастыру
3. Дұрыс/бұрыс тұжырымдар
4. Қазақстандық мысалдар
5. Карта белгілерін тану

## B блок — карта және дерек
1. Масштаб бойынша қашықтық есептеу
2. Климат/гидрология кестесін оқу
3. Екі аймақты салыстыру
4. ГАЖ/ДЗЗ қолданысын түсіндіру

## C блок — зерттеу тапсырмасы
**Тақырып:** «${title}: себептері, салдары, Қазақстандағы көрінісі»

Оқушы:
1. Мәселені тұжырымдайды
2. 2–3 дереккөз/картаға сүйенеді
3. Қорытынды мен ұсыныс жазады

**Критерийлер (20 ұпай):**
- Мәселе қою (4)
- Дерек / карта (6)
- Талдау (6)
- Қорытынды (4)

## Бағалау шкаласы (50 ұпай)
| Ұпай | Баға |
|------|------|
| 45–50 | 5 |
| 35–44 | 4 |
| 25–34 | 3 |
| <25 | Қосымша қолдау |

## Мұғалімге ескертпе
- Дескрипторларды сыныпқа бейімдеңіз
- Инклюзивті нұсқа: қысқартылған C блок
- Академиялық адалдық: өз сөзімен жазу

---
*«География Әлемі» ТЖБ үлгісі — тоқсан жоспарыңызға сәйкес толықтырыңыз.*
`;
}
